def _md_of(skill: str, only: list[str] | None) -> str:
    d = ROOT / "skills" / skill
    out = [f"\n\n<!-- ===== skill: {skill} ===== -->\n", (d / "SKILL.md").read_text(encoding="utf-8")]
    refs = sorted((d / "references").rglob("*.md")) if (d / "references").is_dir() else []
    for r in refs:
        rel = r.relative_to(d / "references")
        if "provenance" in rel.parts or "books" in rel.parts:
            continue
        if only is not None and rel.name not in only:
            continue
        out.append(f"\n\n<!-- ----- {skill}/references/{rel.as_posix()} ----- -->\n" + r.read_text(encoding="utf-8", errors="replace"))
    return "".join(out)


