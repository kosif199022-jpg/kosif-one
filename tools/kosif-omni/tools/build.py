def _rpc(proc, msg):
    proc.stdin.write((json.dumps(msg) + "\n").encode())
    proc.stdin.flush()
    return json.loads(proc.stdout.readline().decode("utf-8"))


def _smoke_stdio(cmd: list[str], cwd: Path, label: str) -> None:
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONDONTWRITEBYTECODE": "1", "KOSIF_ALLOW_CWD": "0"}
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=str(cwd), env=env)
    try:
        r = _rpc(p, {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18"}})
        assert r["result"]["serverInfo"]["name"] == "kosif-omni", r
        p.stdin.write((json.dumps({"jsonrpc": "2.0", "method": "notifications/initialized"}) + "\n").encode())
        p.stdin.flush()
        n = len(_rpc(p, {"jsonrpc": "2.0", "id": 2, "method": "tools/list"})["result"]["tools"])
        r = _rpc(p, {"jsonrpc": "2.0", "id": 3, "method": "tools/call",
                     "params": {"name": "kosif_skill_read", "arguments": {"name": "kosif-omni"}}})
        assert not r["result"]["isError"], r
        r = _rpc(p, {"jsonrpc": "2.0", "id": 4, "method": "tools/call",
                     "params": {"name": "kosif_council_panel", "arguments": {"question": "test", "seed": 1}}})
        assert not r["result"]["isError"], r
        r = _rpc(p, {"jsonrpc": "2.0", "id": 5, "method": "tools/call",
                     "params": {"name": "kosif_light_calc", "arguments": {"op": "inverse_square", "d1": 1, "d2": 2}}})
        assert not r["result"]["isError"], r
        r = _rpc(p, {"jsonrpc": "2.0", "id": 6, "method": "prompts/list"})
        assert r["result"]["prompts"], "no prompts (commands/ missing from bundle?)"
        print(f"  ✓ {label}: handshake + {n} tools + skill/council/script calls + prompts")
    finally:
        p.stdin.close()
        p.wait(timeout=15)
        p.stdout.close()
        p.stderr.close()


