# ── zips ────────────────────────────────────────────────────────────────────
def _skip(p: Path) -> bool:
    return any(x in EXCLUDE_DIRS for x in p.parts) or p.suffix in EXCLUDE_SUFFIX


def add_tree(z: zipfile.ZipFile, src: Path, arc: str, *, skip=None) -> None:
    for p in sorted(src.rglob("*")):
        rel = p.relative_to(src)
        if p.is_dir() or _skip(rel) or (skip and skip(rel)):
            continue
        z.write(p, f"{arc}/{rel.as_posix()}".lstrip("/"))


