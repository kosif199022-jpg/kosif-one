def build_dist() -> None:
    shutil.rmtree(DIST, ignore_errors=True)
    DIST.mkdir(parents=True)
    c = counts()

    # 1) Claude Code / Codex full plugin
    with zipfile.ZipFile(DIST / "kosif-omni-claude-code.zip", "w", zipfile.ZIP_DEFLATED) as z:
        add_tree(z, ROOT, "kosif-omni")

    # 2) ChatGPT plugin (same layout as the earlier plugin (N).zip uploads: files at the zip root)
    keep_roots = {".codex-plugin", "skills"}
    keep_files = {"plugin.json", ".app.json", "mcp.json", "README.md", "CHANGELOG.md"}
    with zipfile.ZipFile(DIST / "kosif-omni-chatgpt-plugin.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(ROOT.rglob("*")):
            rel = p.relative_to(ROOT)
            if p.is_dir() or _skip(rel):
                continue
            if rel.parts[0] in keep_roots or (len(rel.parts) == 1 and rel.name in keep_files):
                z.write(p, rel.as_posix())

    # 3) Claude Desktop extension (.mcpb)
    with zipfile.ZipFile(DIST / "kosif-omni.mcpb", "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("manifest.json", json.dumps(mcpb_manifest(c), ensure_ascii=False, indent=2))
        z.writestr("server/main.py", "import os, sys\nsys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))\n"
                   "from kosif_mcp.__main__ import main\nraise SystemExit(main())\n")
        add_tree(z, ROOT / "mcp-server" / "kosif_mcp", "server/kosif_mcp")
        add_tree(z, ROOT / "skills", "skills")
        add_tree(z, ROOT / "commands", "commands")

    # 4) one zip per skill for claude.ai / Claude Desktop skill upload
    (DIST / "claude-ai-skills").mkdir(exist_ok=True)
    for name in _skills():
        with zipfile.ZipFile(DIST / "claude-ai-skills" / f"{name}.zip", "w", zipfile.ZIP_DEFLATED) as z:
            add_tree(z, ROOT / "skills" / name, name)

    # 5) packs
    shutil.copytree(ROOT / "chatgpt" / "custom-gpt", DIST / "custom-gpt")
    shutil.copytree(ROOT / "claude", DIST / "claude-project")
    shutil.copy(ROOT / "INSTALL.ar.md", DIST / "INSTALL.ar.md")


