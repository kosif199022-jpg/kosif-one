# ── generated reference docs ────────────────────────────────────────────────
def gen_tool_catalog() -> None:
    lines = ["# Tool catalogue (generated by tools/build.py)", "",
             f"{len(REGISTRY)} tools. `RO` = read-only · `RW` = writes (state, files). `gpt` = also exposed to ChatGPT Actions.", ""]
    for t in REGISTRY.values():
        props = t.schema.get("properties", {})
        req = set(t.schema.get("required", []))
        lines.append(f"## `{t.name}` — {'RO' if t.read_only else 'RW'}{' · gpt' if t.gpt else ''}")
        lines.append(t.description)
        if props:
            lines.append("")
            lines.append("| argument | type | required | description |")
            lines.append("|---|---|---|---|")
            for k, v in props.items():
                d = str(v.get("description", "")).replace("|", "\\|").replace("\n", " ")
                lines.append(f"| `{k}` | {v.get('type', 'any')} | {'yes' if k in req else ''} | {d} |")
        lines.append("")
    write(ROOT / "skills/kosif-omni/references/tool-catalog.md", "\n".join(lines))

    fam = ["# Capability map (generated by tools/build.py)", "",
           "| Family | Skills | Tools |", "|---|---|---|"]
    for f in FAMILIES:
        fam.append(f"| {f['title']} | {', '.join(f'`{s}`' for s in f['skills'])} | {', '.join(f'`{x}`' for x in f['tools']) or '—'} |")
    fam += ["", "## All skills", ""]
    for n, v in _skills().items():
        fam.append(f"- `{n}` — {v['description'][:160]}")
    write(ROOT / "skills/kosif-omni/references/capability-map.md", "\n".join(fam) + "\n")


