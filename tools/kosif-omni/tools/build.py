def stamp_manifests() -> dict:
    c = counts()
    d = desc_en(c)
    for rel in (".claude-plugin/plugin.json", ".codex-plugin/plugin.json", "plugin.json"):
        p = ROOT / rel
        j = json.loads(p.read_text(encoding="utf-8"))
        j["version"], j["description"] = VERSION, d
        dump(p, j)
    p = ROOT / ".claude-plugin/marketplace.json"
